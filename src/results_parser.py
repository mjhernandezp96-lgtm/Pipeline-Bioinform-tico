def run_results_parser(tbl_file: str, uniprot_ids: list[str]):
    """Parse results, write CSV and HTML."""
    print("[results_parser] Parsing hmmscan results ...")
    proteins = parse_hmmer_results(tbl_file, uniprot_ids)

    n_hits = sum(1 for p in proteins if p.pfam_family)
    print(f"[results_parser] {n_hits}/{len(proteins)} proteins have Pfam hits")

    write_csv(proteins, FINAL_CSV)
    write_html(proteins, REPORT_HTML)

    return proteins
