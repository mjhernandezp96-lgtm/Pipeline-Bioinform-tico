import csv
import os

from src.models import Protein, PfamResult

FINAL_CSV = "results/final_results.csv"
REPORT_HTML = "results/report.html"


def parse_hmmer_results(tbl_file: str, uniprot_ids: list[str]) -> list[Protein]:
    """Parse hmmscan --tblout output and return Protein objects."""
    best_hits: dict[str, tuple[str, str, float, float]] = {}

    with open(tbl_file) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            fields = line.split()
            if len(fields) < 19:
                continue

            family = fields[0]
            accession = fields[1]
            target = fields[2]
            evalue = float(fields[4])
            score = float(fields[5])

            target = target.split("|")[-1] if "|" in target else target

            if target not in best_hits or evalue < best_hits[target][3]:
                best_hits[target] = (family, accession, score, evalue)

    proteins: list[Protein] = []
    for uid in uniprot_ids:
        p = Protein(uid)
        if uid in best_hits:
            family, accession, score, evalue = best_hits[uid]
            p.pfam_family = family
            p.pfam_accession = accession
            p.score = score
            p.evalue = evalue
        proteins.append(p)

    return proteins


def write_csv(proteins: list[Protein], output_csv: str):
    """Write final results CSV."""
    os.makedirs(os.path.dirname(output_csv) or ".", exist_ok=True)
    with open(output_csv, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["Protein_ID", "Pfam_Family", "Score"])
        for p in proteins:
            writer.writerow([
                p.uniprot_id,
                p.pfam_family if p.pfam_family else "No hit",
                f"{p.score:.2f}" if p.score else "",
            ])
    print(f"[results_parser] CSV saved to {output_csv}")


